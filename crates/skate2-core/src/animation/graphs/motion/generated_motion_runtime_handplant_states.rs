#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn all_authored_handplant_leaves_use_each_actual_owner_once() {
        let states = &super::super::super::data::STATES;
        let mut count = 0;
        for (index, state) in states.iter().enumerate() {
            let mut cursor = index as u16;
            let mut in_tree = false;
            let mut slots = Vec::new();
            while cursor != u16::MAX {
                in_tree |= matches!(cursor, 20 | 717);
                let s = &states[usize::from(cursor)];
                slots.extend(s.behaviours.index..s.behaviours.index + s.behaviours.count);
                cursor = s.parent;
            }
            if in_tree {
                slots.sort_unstable();
                assert_eq!(
                    expected(index as u16, state.update_address),
                    Some(slots.as_slice()),
                    "{}",
                    state.name
                );
                assert!(slots.windows(2).all(|w| w[0] < w[1]));
                count += 1;
            }
        }
        assert_eq!(count, 44);
    }
}
