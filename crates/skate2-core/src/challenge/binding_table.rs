//! Every `Lua::Binding::BindModule` table (`0x82aaf0b8` callers) and the
//! `cMsg*` exporters from `BindAllMessageExportersToLua` (`0x828cf970`),
//! generated from the debug executable. A function entry names the native;
//! an enum entry carries `BindEnum<T>` values.

/// `li r3, 0; blr`: the shared empty native (identical-code-folded no-ops).
pub const EMPTY_NATIVE: u32 = 0x8278_4530;

pub enum Entry {
    /// Name and native address.
    Function(&'static str, u32),
    NumberEnum(&'static str, &'static [(&'static str, f32)]),
    StringEnum(&'static str, &'static [(&'static str, &'static str)]),
}

pub struct Module {
    /// `None`: bound into the globals table (`BindModule(lua, NULL, ...)`).
    pub name: Option<&'static str>,
    /// The `BIND` table address, distinguishing same-named bind sites.
    pub table: u32,
    pub entries: &'static [Entry],
}

