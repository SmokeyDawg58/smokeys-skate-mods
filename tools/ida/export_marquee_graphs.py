"""Read the native marquee and photographer AI and motion delegate declarations in IDA and
emit their Rust tables. Read-only: the IDB is never changed."""
from pathlib import Path
import ida_bytes as b
import idautils

AI = (('marquee', 'HCDelegate_marquee'), ('photographer', 'HCDelegate_Photographer'))
MOTION = (('marquee', 'HCDelegate_motiongraph_marquee'),
          ('photographer', 'HCDelegate_Motiongraph_Photographer'))


def tables(delegate):
    names = list(idautils.Names())
    addresses = {n.split('@')[0][2:]: a for a, n in names
                 if n.startswith('?k') and '@' + delegate + '@' in n}

    def text(a):
        value = b.get_strlit_contents(b.get_dword(a), -1, 0)
        return value.decode('utf-8') if value else ''

    def section(a):
        return 'Section { count: %d, index: %d }' % (b.get_word(a), b.get_word(a + 2))

    def rows(key, stride):
        a = addresses[key]
        return range(a, a + b.get_item_size(a), stride)

    def string(value):
        return '"' + value.replace('\\', '\\\\').replace('"', '\\"') + '"'

    out = {}
    out['ATTRIBUTES'] = ('Attribute', ['Attribute { key: %s, value: %s }' % (string(text(a)), string(text(a + 4)))
                                       for a in rows('Attribs', 8)])
    out['STATES'] = ('StateDeclaration', [
        'StateDeclaration { name: %s, interrupt_type: %d, active: %s, interrupt_target: %d, parent: %d, '
        'expression: %d, children: %s, behaviours: %s, transitions: %s, update_address: %d, trailing: %d }'
        % (string(text(a)), b.get_byte(a + 4), 'true' if b.get_byte(a + 5) else 'false', b.get_word(a + 6),
           b.get_word(a + 8), b.get_word(a + 10), section(a + 12), section(a + 16), section(a + 20),
           b.get_dword(a + 24), b.get_dword(a + 28)) for a in rows('States', 32)])
    out['TRANSITIONS'] = ('TransitionDeclaration', [
        'TransitionDeclaration { name: %s, priority: %d, target: %d, expression: %d, hooks: %s }'
        % (string(text(a)), b.get_byte(a + 4), b.get_word(a + 6), b.get_word(a + 8), section(a + 10))
        for a in rows('Transitions', 16)])
    out['BEHAVIOURS'] = ('BehaviourDeclaration', [
        'BehaviourDeclaration { name: %s, parent: %d, attributes: %s, parameters: %s }'
        % (string(text(a)), b.get_word(a + 4), section(a + 6), section(a + 10)) for a in rows('Behaviours', 16)])
    out['CONDITIONS'] = ('ConditionDeclaration', [
        'ConditionDeclaration { name: %s, attributes: %s }' % (string(text(a)), section(a + 4))
        for a in rows('Conditions', 8)])
    indices = [b.get_word(a) for a in rows('IndexArray', 2)]
    return addresses, out, indices


def emit(destination, title, families):
    lines = ['//! ' + title + ' Generated by tools/ida/export_marquee_graphs.py.',
             'use crate::generated_action_load::{Attribute, BehaviourDeclaration, ConditionDeclaration, '
             'Section, StateDeclaration, TransitionDeclaration};']
    for module, delegate in families:
        addresses, out, indices = tables(delegate)
        lines += ['', '/// `%s` (kStates %#x).' % (delegate, addresses['States']), 'pub(crate) mod %s {' % module,
                  '    use super::*;']
        for key in ('ATTRIBUTES', 'STATES', 'TRANSITIONS', 'BEHAVIOURS', 'CONDITIONS'):
            kind, rows = out[key]
            lines.append('    pub(crate) const %s: [%s; %d] = [' % (key, kind, len(rows)))
            lines += ['        %s,' % row for row in rows]
            lines.append('    ];')
        lines.append('    pub(crate) const INDICES: [u16; %d] = %s;' % (len(indices), indices))
        lines.append('}')
    with Path(destination).open('w', encoding='utf-8', newline='\n') as file:
        file.write('\n'.join(lines) + '\n')


def export(ai_destination, motion_destination):
    emit(ai_destination, 'Native HCDelegate_marquee and HCDelegate_Photographer declarations.', AI)
    emit(motion_destination, 'Native HCDelegate_motiongraph_marquee and HCDelegate_Motiongraph_Photographer '
         'declarations.', MOTION)
