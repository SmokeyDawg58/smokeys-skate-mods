"""Emit shared Rust declaration types from original IDA plugin evidence."""
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
data=json.loads((ROOT/'docs/evidence/pedestrian-native-plugins-2026-09-30.json').read_text())
def val(v):
 if isinstance(v,str):return json.dumps(v)
 if isinstance(v,bool):return str(v).lower()
 if isinstance(v,dict):return 'Section { '+', '.join(k+': '+str(x) for k,x in v.items())+' }'
 return str(v)
out=['//! Original generated plugin tables. Generated by tools/ida/emit_pedestrian_plugins.py.',
'use crate::generated_action_load::{Attribute,BehaviourDeclaration,ConditionDeclaration,Section,StateDeclaration,TransitionDeclaration};']
for family,g in data.items():
 out+=['pub(crate) mod '+family+' {','use super::*;']
 for key,typ in [('attributes','Attribute'),('states','StateDeclaration'),('transitions','TransitionDeclaration'),('behaviours','BehaviourDeclaration'),('conditions','ConditionDeclaration')]:
  out+=['pub(crate) const '+key.upper()+': ['+typ+'; '+str(len(g[key]))+'] = [']
  out += [typ+' { '+', '.join(k+': '+val(v) for k,v in row.items())+' },' for row in g[key]]
  out+= ['];']
 out+=['pub(crate) const INDICES: [u16; '+str(len(g['indices']))+'] = '+str(g['indices'])+';','}']
(ROOT/'crates/skate2-core/src/living_world/pedestrians/pedestrian_plugin_data.rs').write_text('\n'.join(out)+'\n')
